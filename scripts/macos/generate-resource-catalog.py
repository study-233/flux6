#!/usr/bin/env python3
"""Compile pinned Go resource manifests into the service's signed executable."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "apps/macos/Sources/FreeV6System/ApprovedResources.generated.swift"


def render():
    runtime = json.loads((ROOT / "internal/mihomo/runtime-assets.json").read_text())
    geodata = json.loads((ROOT / "internal/mihomo/geodata-assets.json").read_text())
    lines = ["// Generated by scripts/macos/generate-resource-catalog.py; do not edit.",
             "extension ApprovedResourceCatalog {",
             f"    static let coreVersion = {json.dumps(runtime['version'])}",
             "    static let pinned: [ApprovedResource] = ["]
    quote = json.dumps
    for asset in runtime["assets"]:
        if asset["os"] != "darwin":
            continue
        resource_id = f"mihomo-darwin-{asset['arch']}-{runtime['version']}"
        lines.append(f"        .init(id: {quote(resource_id)}, filename: {quote(resource_id)},")
        lines.append(f"              sha256: {quote(asset['binarySha256'])}, size: nil,")
        lines.append(f"              archiveSHA256: {quote(asset['sha256'])}, architecture: {quote(asset['arch'])}, archiveName: {quote(asset['archive'])}),")
    group = "geodata-" + geodata["revision"]
    for asset in geodata["assets"]:
        lines.append(f"        .init(id: {quote(group + '/' + asset['name'])}, filename: {quote(group + '-' + asset['name'])},")
        lines.append(f"              sha256: {quote(asset['sha256'])}, size: {asset['size']},")
        lines.append("              archiveSHA256: nil, architecture: nil),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.error("Service catalog is stale; run this script without --check")
    else:
        OUTPUT.write_text(content)
